"""Generate the appendices of the CPAT-AI Model book (the website's CPAT-AI Model tab): the equation list shared by
Excel-AI and CPAT Python, in the notation of the methodology (appendix A) and with the CPAT code names (appendix B).

    python make_qmd.py     the two appendices, from coded/cpat_documentation/equations/Equations*.qmd
    quarto render          the HTML book in ../CPAT_model_documentation_html/

The chapters (index, 01-08) are written here by hand; the equation list is generated from
coded/cpat_documentation/equations/equations.yaml (make_equations.py there): edit that, never the appendices.
Every equation gets an anchor the chapters link to: A_Equations.qmd#eqlist-M4-3 and B_Equations_codes.qmd#eqcode-M4-3.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'CPAT_ai_documentation_qmd'))
import make_qmd as ai                                    # noqa: E402  (the converter shared by the books)

EQ = 'coded/cpat_documentation/equations'
ITEM = re.compile(r'^\*\*([MADB]\d+(?:\.\d+)*)\s')


def equations(src, title, sec_id, prefix, intro):
    with open(os.path.join(ai.REPO, src), encoding='utf-8') as f:
        text = re.sub(r'\A---\n.*?\n---\n', '', f.read(), flags=re.S)
    lines = []
    for line in text.splitlines():
        m = ITEM.match(line)
        if m:
            line = f'[]{{#{prefix}-{m.group(1).replace(".", "-")}}}' + line
        if not line.startswith('!['):
            line = ai.LINK.sub(lambda mm: ai.fix_link(mm, os.path.dirname(src)), line)
        lines.append(line)
    body = '\n'.join(lines).strip()
    for old, new in (('# Appendix A: mitigation adjustments', '# Adjustments: mitigation'),
                     ('# Appendix B: distribution adjustments', '# Adjustments: distribution'),
                     ('# Appendix: symbols and codes', '# Symbols and codes'), ('## How to read this list', '# How to read this list')):
        body = body.replace(old, new)
    body = ai.demote(body)
    return (f'<!-- Generated by make_qmd.py from {src}: edit equations.yaml, then run make_equations.py and '
            f'python make_qmd.py -->\n\n# {title} {{#{sec_id}}}\n\n{intro}\n\n'
            f'*Source: [`{src}`]({ai.GITHUB}{src}), generated from `{EQ}/equations.yaml`.*\n\n{body}\n')


def main():
    out = {
        'A_Equations.qmd': equations(
            f'{EQ}/Equations.qmd', 'Equation list: methodology notation', 'sec-eqlist', 'eqlist',
            'Every equation of the model, in the order the model computes it, in the notation of the CPAT methodology. '
            'Excel-AI computes each one in its workbook and CPAT Python in one function that cites its id '
            '(`EQ-M4.3`). The chapters explain them; this list is the reference.'),
        'B_Equations_codes.qmd': equations(
            f'{EQ}/Equations_codes.qmd', 'Equation list: CPAT code names', 'sec-eqcodes', 'eqcode',
            'The same equations, ids and order as appendix A, written with the CPAT variable codes that both '
            'Excel-AI (row codes) and CPAT Python (variable names) use.'),
    }
    for name, text in out.items():
        with open(os.path.join(HERE, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', name)


if __name__ == '__main__':
    main()
