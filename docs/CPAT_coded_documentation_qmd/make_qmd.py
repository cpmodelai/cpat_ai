"""Generate the Coded CPAT book (the website's Coded CPAT tab, D12): the guide chapters written beside the code, and
appendices generated from the code and data, so they stay current. The sources are the masters: edit them, never
the generated chapters.

    python make_qmd.py            the chapters and appendices (keeps the last test status)
    python make_qmd.py --tests    also runs the tests (about a minute) and rewrites the test status
    quarto render                 the HTML book in ../CPAT_coded_documentation_html/

The guide chapters (index, 01-11 Part I and Part II, J glossary) are written here, in this folder (since 2026-10-30;
they were copied from `coded/cpat_documentation/guide/`). Sources of the appendices: the equation lists, `data/Public01/tidy/_manifest.csv`
(database tables), `data/inputs/scenarios_excel_ai.csv` (inputs), `coded/cpat_model/core/variables.csv` (variables),
`coded/cpat_testing/compare/known_differences.py` and the bugs section of `coded/TODO.md` (bugs), the spec, the norms
and the plan.
"""
import csv
import datetime
import os
import re
import shutil
import subprocess
import sys
import xml.etree.ElementTree as ET

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'CPAT_ai_documentation_qmd'))
import make_qmd as ai                                    # noqa: E402  (the CPAT-AI book's converter)

REPO = ai.REPO
CODED = os.path.join(REPO, 'coded')
DOC = 'coded/cpat_documentation'
GENERATED = ['A_Equations.qmd', 'B_Equations_codes.qmd', 'C_Database_tables.qmd', 'D_Inputs.qmd', 'E_Variables.qmd',
             'F_Bugs.qmd', 'G_Spec.qmd', 'H_Norms.qmd', 'I_Plan.qmd']


def cell(x):
    """A table cell: no pipes or newlines; currency dollars escaped."""
    return ai.escape_dollars(str(x).replace('|', '/').replace('\n', ' ').strip())


def table(header, rows):
    out = ['| ' + ' | '.join(header) + ' |', '|' + '---|' * len(header)]
    out += ['| ' + ' | '.join(cell(x) for x in r) + ' |' for r in rows]
    return '\n'.join(out) + '\n'


def chapter(title, sec_id, source, body):
    return (f'<!-- Generated by make_qmd.py from {source}: edit the source, then run python make_qmd.py -->\n\n'
            f'# {title} {{#{sec_id}}}\n\n{body}')


def convert_qmd(src_rel, title, sec_id):
    """A Quarto source as a chapter: its front matter replaced by the chapter heading; links to GitHub."""
    with open(os.path.join(REPO, src_rel), encoding='utf-8') as f:
        text = re.sub(r'\A---\n.*?\n---\n', '', f.read(), flags=re.S)
    src_dir = os.path.dirname(src_rel)
    lines = [ai.LINK.sub(lambda m: ai.fix_link(m, src_dir), line) if not line.startswith('![') else line
             for line in text.splitlines()]
    return chapter(title, sec_id, src_rel, f'*Source: [`{src_rel}`]({ai.GITHUB}{src_rel}).*\n\n' + '\n'.join(lines))


def database_tables():
    path = os.path.join(REPO, 'data', 'Public01', 'tidy')
    with open(os.path.join(path, '_manifest.csv'), encoding='utf-8') as f:
        man = list(csv.DictReader(f))
    rows = []
    for m in sorted((r for r in man if r['kind'] != 'cells layout'), key=lambda r: r['table']):
        with open(os.path.join(path, m['table'] + '.csv'), encoding='utf-8') as f:
            cols = next(csv.reader(f), [])
        rows.append((f"`{m['table']}`", ', '.join(cols), m['keys'], m['rows'], m['legacy_tab'],
                     'yes' if m['proprietary'] == 'yes' else ''))
    intro = (f'Every table of the database (`data/Public01/tidy/`, {len(rows)} tables; source `data/Public01/tidy/_manifest.csv`): its '
             'columns, the keys of a row, the number of rows in the dummy database, the legacy tab it comes from, and '
             'whether it is proprietary (energy consumption is treated as proprietary too, with the energy balances). '
             'Column meanings and units: `data/README.md` and `data/catalog.csv`.\n\n')
    return chapter('Database tables', 'sec-app-tables', 'data/Public01/tidy/_manifest.csv',
                   intro + table(['Table', 'Columns', 'Keys', 'Rows', 'Legacy tab', 'Proprietary'], rows))


def inputs():
    with open(os.path.join(REPO, 'data', 'inputs', 'scenarios_excel_ai.csv'), encoding='utf-8') as f:
        rows = [(f"`{r['name']}`", r['label'], r['unit'], r['1'], r['row']) for r in csv.DictReader(f)
                if r['name'] and not r['name'].startswith('_')]
    intro = (f'Every input of a scenario set ({len(rows)}; source: Excel-AI\'s scenario set '
             '`data/inputs/scenarios_excel_ai.csv`), in ScenarioDefinition order: its name (`NameOfParameter`), what '
             'it is, its unit, its value in the baseline (scenario 1) and its row in Excel-AI\'s ScenarioDefinition.\n\n')
    return chapter('Inputs', 'sec-app-inputs', 'data/inputs/scenarios_excel_ai.csv',
                   intro + table(['Name', 'Label', 'Unit', 'Baseline', 'Row'], rows))


def variables():
    with open(os.path.join(CODED, 'cpat_model', 'core', 'variables.csv'), encoding='utf-8') as f:
        rows = list(csv.DictReader(f))
    stems = {}
    for r in rows:
        s = stems.setdefault(r['variable'], {'desc': r['description'].split(' | ')[0], 'unit': r['unit'], 'n': 0,
                                             'code': r['code']})
        s['n'] += 1
    out = [(f'`{v}`', s['desc'], s['unit'], s['n'], f"`{s['code']}`") for v, s in stems.items()]
    intro = (f'Every variable of the mitigation results ({len(out)} variables, {len(rows)} rows; source '
             '`coded/cpat_model/core/variables.csv`), in the order of Excel-AI\'s Mitigation sheet: its description, '
             'unit, number of rows (sector and fuel combinations) and the output code of its first row.\n\n')
    return chapter('Variables', 'sec-app-variables', 'coded/cpat_model/core/variables.csv',
                   intro + table(['Variable', 'Description', 'Unit', 'Rows', 'First code'], out))


def bugs():
    sys.path.insert(0, CODED)
    from cpat_testing.compare.known_differences import KNOWN
    with open(os.path.join(CODED, 'TODO.md'), encoding='utf-8') as f:
        todo = f.read()
    m = re.search(r'^## Excel-AI bugs.*?\n(.*?)(?=^## )', todo, flags=re.S | re.M)
    known = table(['Bug', 'Codes that differ from Excel-AI (country prefix and scenario left out)'],
                  [(b, ', '.join(f'`{c}`' for c in codes)) for b, codes in KNOWN.items()])
    body = ('**The rule** (user 2026-10-29): a bug in the prototype (Excel-AI does not compute what it means to) is not '
            'copied: Coded CPAT fixes it and it is registered (`excel_ai/core/BUGS.md`, prototype bugs M); an issue (a '
            'potential improvement) is logged and copied as it is for now.\n\n'
            '## The bugs Coded CPAT found\n\n' + (m.group(1).strip() if m else '') + '\n\n'
            '## Known differences\n\nThe codes where Coded CPAT differs from Excel-AI\'s stored values because it fixes '
            'a bug still open in the prototype (`coded/cpat_testing/compare/known_differences.py`); the tests check '
            'that they differ, and the entry is deleted when Excel-AI ships the fix.\n\n' + known)
    return chapter('Excel-AI bugs and known differences', 'sec-app-bugs', 'coded/TODO.md, known_differences.py', body)


def test_status():
    """Run the tests (from coded/) and write _test_status.md: totals, one row per test file, the mitigation blocks."""
    xml = os.path.join(HERE, '.pytest_status.xml')
    t0 = datetime.datetime.now()
    subprocess.run([sys.executable, '-m', 'pytest', '-q', 'cpat_testing', f'--junitxml={xml}', '-p', 'no:cacheprovider'],
                   cwd=CODED, capture_output=True)
    root = ET.parse(xml).getroot()
    os.remove(xml)
    cases = root.iter('testcase')
    files, blocks = {}, []
    for c in cases:
        name = c.get('classname').split('.')[-1] + '.py'
        ok = not any(ch.tag in ('failure', 'error') for ch in c)
        f = files.setdefault(name, [0, 0, 0.0])
        f[0 if ok else 1] += 1
        f[2] += float(c.get('time') or 0)
        if name == 'test_mitigation.py' and '[' in c.get('name'):
            blocks.append((c.get('name').split('[', 1)[1].rstrip(']'), 'pass' if ok else '**FAIL**'))
    commit = subprocess.run(['git', 'rev-parse', '--short', 'HEAD'], cwd=REPO, capture_output=True, text=True).stdout.strip()
    passed, failed = sum(v[0] for v in files.values()), sum(v[1] for v in files.values())
    head = (f'*Last run: {t0:%Y-%m-%d %H:%M}, commit `{commit}`: **{passed} passed, {failed} failed**. '
            'Regenerate with `python make_qmd.py --tests`.*\n\n')
    text = (head + table(['Test file', 'Passed', 'Failed', 'Seconds'],
                         [(f'`{k}`', v[0], v[1], f'{v[2]:.0f}') for k, v in sorted(files.items())])
            + '\nMitigation blocks against Excel-AI (Egypt, scenarios 1 and 2, every code and year):\n\n'
            + table(['Block', 'Result'], blocks))
    with open(os.path.join(HERE, '_test_status.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('<!-- Generated by make_qmd.py --tests -->\n\n' + text)
    print(f'tests: {passed} passed, {failed} failed')


def main():
    for old in GENERATED:                                     # the appendices are rewritten; the guide chapters
        if os.path.exists(os.path.join(HERE, old)):           # (index, 01-11, J) are written here by hand
            os.remove(os.path.join(HERE, old))
    eq = f'{DOC}/equations'
    out = {'A_Equations.qmd': convert_qmd(f'{eq}/Equations.qmd', 'Equation list: methodology notation', 'sec-app-eq'),
           'B_Equations_codes.qmd': convert_qmd(f'{eq}/Equations_codes.qmd', 'Equation list: CPAT code names',
                                                'sec-app-eq-codes'),
           'C_Database_tables.qmd': database_tables(), 'D_Inputs.qmd': inputs(), 'E_Variables.qmd': variables(),
           'F_Bugs.qmd': bugs(),
           'G_Spec.qmd': convert_qmd(f'{DOC}/project/Spec.qmd', 'Specification and design decisions', 'sec-app-spec'),
           'H_Norms.qmd': ai.convert('coded/NORMS.md', 'Python norms', 'sec-app-norms'),
           'I_Plan.qmd': ai.convert('coded/TODO.md', 'The plan and open work', 'sec-app-plan')}
    for name, text in out.items():
        with open(os.path.join(HERE, name), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text.rstrip() + '\n')
    shutil.copytree(os.path.join(REPO, DOC, 'project', 'figures'), os.path.join(HERE, 'figures'), dirs_exist_ok=True)
    if '--tests' in sys.argv or not os.path.exists(os.path.join(HERE, '_test_status.md')):
        test_status()
    print('wrote', ', '.join(out))


if __name__ == '__main__':
    main()
