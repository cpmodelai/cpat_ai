"""Generate the chapters of the Coded CPAT book (the website's Coded CPAT tab, D12) from the documents kept beside
the code in coded/. The sources stay the masters: edit them, never the generated chapters.

Run from this folder: python make_qmd.py, then quarto render.
Markdown sources go through the CPAT-AI book's converter (headings, currency dollars, links to GitHub); Quarto
sources (the spec, the equation lists) keep their maths: only the front matter is replaced by a chapter heading and
relative links point to GitHub. The spec's figures are copied next to the chapters.
"""
import os
import re
import shutil
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(HERE, '..', 'CPAT_ai_documentation_qmd'))
import make_qmd as ai                                    # noqa: E402  (the CPAT-AI book's converter)

DOC = 'coded/cpat_documentation'
# (source relative to the repository, chapter file, chapter title or None for the source's own, section id)
CHAPTERS = [
    ('coded/README.md', '01_Overview.qmd', 'Coded CPAT: overview', 'sec-overview'),
    (f'{DOC}/developer/dev_documentation.md', '02_Developer_Guide.qmd', None, 'sec-developer'),
    (f'{DOC}/project/Spec.qmd', '03_Spec.qmd', 'Specification and plan', 'sec-spec'),
    (f'{DOC}/equations/Equations.qmd', '04_Equations.qmd', 'Equation list: methodology notation', 'sec-equations'),
    (f'{DOC}/equations/Equations_codes.qmd', '05_Equations_codes.qmd', 'Equation list: CPAT code names',
     'sec-equations-codes'),
    ('coded/NORMS.md', '06_Norms.qmd', 'Python norms', 'sec-norms'),
    ('coded/TODO.md', '07_Plan.qmd', 'The plan and open work', 'sec-plan'),
]


def convert_qmd(src_rel, title, sec_id):
    """A Quarto source as a chapter: its front matter replaced by the chapter heading, headings kept."""
    with open(os.path.join(ai.REPO, src_rel), encoding='utf-8') as f:
        text = f.read()
    text = re.sub(r'\A---\n.*?\n---\n', '', text, flags=re.S)
    src_dir = os.path.dirname(src_rel)
    lines = [ai.LINK.sub(lambda m: ai.fix_link(m, src_dir), line) if not line.startswith('![') else line
             for line in text.splitlines()]
    header = [f'<!-- Generated by make_qmd.py from {src_rel}: edit the source, then run python make_qmd.py -->', '',
              f'# {title} {{#{sec_id}}}', '', f'*Source: [`{src_rel}`]({ai.GITHUB}{src_rel}).*', '']
    return '\n'.join(header + lines).rstrip() + '\n'


def main():
    for src, dest, title, sec in CHAPTERS:
        text = convert_qmd(src, title, sec) if src.endswith('.qmd') else ai.convert(src, title, sec)
        with open(os.path.join(HERE, dest), 'w', encoding='utf-8', newline='\n') as f:
            f.write(text)
        print('wrote', dest)
    shutil.copytree(os.path.join(ai.REPO, DOC, 'project', 'figures'), os.path.join(HERE, 'figures'), dirs_exist_ok=True)


if __name__ == '__main__':
    main()
