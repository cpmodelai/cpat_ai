"""Generate the chapters of the CPAT-AI documentation that come from documents kept beside the code.

Run from this folder: python make_qmd.py, then quarto render.
The sources stay the masters: edit them, never the generated chapters. For each source the first level-1
heading becomes the chapter title (or the title given below), the other headings move so the highest is level 2,
dollar signs outside code are escaped (they are currency, not math), and relative links point to the file on GitHub.
Two generated chapters (2026-10-31: few chapters, each with sections): the mitigation prototype (its Documentation)
and its methods (one section per method note). Also writes _counts.md (the bug and issue counts of
excel_ai/core/BUGS.md and ISSUES.md) for chapter 1.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, '..', '..'))
GITHUB = 'https://github.com/cpmodelai/cpat_ai/blob/main/'

DECK = '```{=html}\n<div class="decks">\n<a class="deck-card" href="../presentations/01_CPAT-AI_Overview_latest.pptx" style="display:flex;gap:14px;align-items:center;text-decoration:none;border:1px solid #dee2e6;border-radius:6px;padding:10px;margin:0 0 12px;max-width:640px;color:inherit"><img src="../presentations/thumbs/01_CPAT-AI_Overview_latest.png" alt="First slide of CPAT-AI overview: the mitigation prototype" style="width:200px;border-radius:4px;border:1px solid #dee2e6;margin:0"><span><b style="color:#2780e3">CPAT-AI overview: the mitigation prototype</b><br><span style="font-size:.9em;color:#6c757d">Status, user guide, results · PowerPoint, latest version</span></span></a>\n</div>\n```\n'

# The generated chapters: (chapter file, chapter title, section id, lead text, parts). The first part is the body of
# the chapter (its headings as they are); every further part becomes one section: (source relative to the repository,
# section title or None for the source's own, section id, heading of the one section to take or None for all).
# The method of every block is in the CPAT-AI Model tab (../CPAT_model_documentation_qmd/, written by hand since
# 2026-10-31); this book keeps what is particular to the workbook.
METHODS = 'excel_ai/mitigation/docs/methods/'
MODEL = '../CPAT_model_documentation_html/'
CHAPTERS = [
    ('02_Mitigation_Prototype.qmd', 'The mitigation module', 'sec-mitigation',
     DECK + '\n::: {.callout-tip appearance="simple"}\nThe method of every block, with its equations and pseudocode, is '
     f'in the **CPAT-AI Model** tab ([open it]({MODEL}index.html)), shared by Excel-AI and CPAT Python. This chapter '
     'is the workbook: how to open and use it, its sections, many scenarios, and its data tabs.\n:::\n',
     [('excel_ai/mitigation/docs/Documentation.md', None, None, None),
      (METHODS + 'Macro_and_results.md', 'Running many scenarios', 'sec-many-scenarios', 'Multiple scenarios'),
      (METHODS + 'Data_tabs.md', 'The data tabs', 'sec-data-tabs', None)]),
]
# Chapter files generated by earlier layouts (one chapter per source), removed when the chapters are written
OLD = ['03_Methods.qmd', '03_Mitigation_Prototype.qmd', '04_Prices.qmd', '05_Power.qmd', '06_Transport.qmd', '07_Emissions.qmd',
       '08_ETS.qmd', '09_Macro_and_Results.qmd', '10_Distribution_Tab.qmd', '11_Data_Tabs.qmd']

HEADING = re.compile(r'^(#{1,6})\s+(.*)$')
FENCE = re.compile(r'^\s*(```|~~~)')
LINK = re.compile(r'(\]\()([^)\s]+)(\))')


def escape_dollars(line):
    """Escape $ outside inline code spans."""
    parts = re.split(r'(`[^`]*`)', line)
    return ''.join(p if p.startswith('`') else re.sub(r'(?<!\\)\$', r'\\$', p) for p in parts)


def demote(text, by=1):
    """Every heading outside fenced code one level lower (a chapter becomes a section of a longer chapter)."""
    out, in_fence = [], False
    for line in text.splitlines():
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence and HEADING.match(line):
            m = HEADING.match(line)
            line = '#' * min(6, len(m.group(1)) + by) + ' ' + m.group(2)
        out.append(line)
    return '\n'.join(out)


def fix_link(match, src_dir):
    target = match.group(2)
    if re.match(r'^(https?:|mailto:|#)', target):
        return match.group(0)
    path, _, anchor = target.partition('#')
    resolved = os.path.normpath(os.path.join(src_dir, path)).replace(os.sep, '/')
    return match.group(1) + GITHUB + resolved + ('#' + anchor if anchor else '') + match.group(3)


def extract(lines, heading):
    """The lines of one section of a source: from the heading that starts with `heading` to the next heading of the
    same or a higher level (outside fenced code)."""
    in_fence, start, level = False, None, None
    for i, line in enumerate(lines):
        if FENCE.match(line):
            in_fence = not in_fence
            continue
        m = None if in_fence else HEADING.match(line)
        if m and start is None and m.group(2).startswith(heading):
            start, level = i, len(m.group(1))
        elif m and start is not None and len(m.group(1)) <= level:
            return lines[start:i]
    return lines[start:]


def convert(src_rel, title, sec_id, only=None):
    with open(os.path.join(REPO, src_rel), encoding='utf-8') as f:
        lines = f.read().splitlines()
    if only:
        lines = extract(lines, only)
    src_dir = os.path.dirname(src_rel)

    # Headings outside fenced code
    in_fence, headings = False, []
    for i, line in enumerate(lines):
        if FENCE.match(line):
            in_fence = not in_fence
        elif not in_fence and HEADING.match(line):
            headings.append(i)
    first = headings[0]
    source_title = HEADING.match(lines[first]).group(2).strip()
    rest = [len(HEADING.match(lines[i]).group(1)) for i in headings[1:]]
    shift = 2 - min(rest) if rest else 0

    out, in_fence = [], False
    for i, line in enumerate(lines):
        if i == first:
            continue
        if FENCE.match(line):
            in_fence = not in_fence
            out.append(line)
            continue
        if in_fence:
            out.append(line)
            continue
        m = HEADING.match(line) if i in headings else None
        if m:
            level = min(6, max(2, len(m.group(1)) + shift))
            text = re.sub(r'^\d+[a-z]?(\.\d+)*\.?\s+', '', m.group(2))   # Quarto numbers the sections
            line = '#' * level + ' ' + text
        line = escape_dollars(line)
        line = LINK.sub(lambda mm: fix_link(mm, src_dir), line)
        out.append(line)

    while out and not out[0].strip():
        out.pop(0)
    header = [
        f'<!-- Generated by make_qmd.py from {src_rel}: edit the source, then run python make_qmd.py -->',
        '',
        f'# {title or source_title} {{#{sec_id}}}',
        '',
        f'*Source: [`{src_rel}`]({GITHUB}{src_rel}).*',
        '',
    ]
    return '\n'.join(header + out).rstrip() + '\n'


def counts():
    out = []
    for name in ('BUGS.md', 'ISSUES.md'):
        with open(os.path.join(REPO, 'excel_ai', 'core', name), encoding='utf-8') as f:
            text = f.read()
        version = re.search(r'^# .*\((v[\d.]+)\)', text, re.M)
        line = next(l for l in text.splitlines() if l.startswith('**') and not l.startswith('**The rule'))
        out.append(f'- {line}' + (f' *(register {version.group(1)}, `excel_ai/core/{name}`)*' if version else ''))
    return '<!-- Generated by make_qmd.py from excel_ai/core/BUGS.md and ISSUES.md -->\n\n' + '\n'.join(out) + '\n'


def chapter(title, sec_id, lead, parts):
    """A chapter: the first part as the body, every further part as one section."""
    src, _, _, only = parts[0]
    text = convert(src, title, sec_id, only)
    head = f'# {title} {{#{sec_id}}}\n'
    text = text.replace(head, head + '\n' + lead, 1) if lead else text
    srcs = ', '.join(p[0] for p in parts)
    text = text.replace(f'from {src}: edit the source,', f'from {srcs}: edit the sources,', 1)
    for src, t, sec, only in parts[1:]:
        part = convert(src, t, sec, only)
        part = part.split('\n', 2)[2]                       # the generated-by line goes
        text = text.rstrip() + '\n\n' + demote(part).strip() + '\n'
    return text


def main():
    for old in OLD:
        if os.path.exists(os.path.join(HERE, old)):
            os.remove(os.path.join(HERE, old))
    for dest, title, sec, lead, parts in CHAPTERS:
        with open(os.path.join(HERE, dest), 'w', encoding='utf-8', newline='\n') as f:
            f.write(chapter(title, sec, lead, parts))
        print('wrote', dest)
    with open(os.path.join(HERE, '_counts.md'), 'w', encoding='utf-8', newline='\n') as f:
        f.write(counts())
    print('wrote _counts.md')


if __name__ == '__main__':
    main()
