"""Write the two versions of the equation list from its one source, equations.yaml.

    Equations.qmd        the equations in the notation of the methodology (Greek letters, index letters)
    Equations_codes.qmd  the same equations with CPAT variable codes (the codes map) instead of symbols

Both are generated: edit equations.yaml, then run this script and ../make_docs.py (Word copies).
The code of Coded CPAT cites the equation ids (EQ-<id>) in its docstrings (coded/NORMS.md section 1).

Usage (from coded/cpat_documentation/equations):  python make_equations.py
"""

from __future__ import annotations

from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "equations.yaml"

VERSIONS = {
    "greek": ("Equations.qmd", "Equation list: methodology notation"),
    "codes": ("Equations_codes.qmd", "Equation list: CPAT code names"),
}


def equation_block(eq: dict, form: str) -> str:
    """One equation: id and title, the formula, what it ranges over, then its sources."""
    lines = [f"**{eq['id']}  {eq['title']}**" + ("" if eq.get("kind", "core") == "core" else "  *(adjustment)*"), ""]
    formula = eq[form].strip()
    lines += ["$$", formula, "$$", ""]
    details = []
    if eq.get("over"):
        details.append(f"Over {eq['over']}.")
    if eq.get("note"):
        details.append(eq["note"].strip())
    sources = []
    if eq.get("doc"):
        sources.append(f"methodology: {eq['doc']}")
    if eq.get("excel"):
        sources.append(f"Excel-AI: {eq['excel']}")
    if sources:
        details.append("Source: " + "; ".join(sources) + ".")
    if details:
        lines += [" ".join(details), ""]
    return "\n".join(lines)


def symbol_table(symbols: list[dict]) -> str:
    rows = ["| Symbol | Code | Meaning | Unit | Notation from |", "|---|---|---|---|---|"]
    for s in symbols:
        rows.append(f"| ${s['symbol']}$ | `{s.get('code', '')}` | {s['meaning']} | {s.get('unit', '')} | {s.get('from', '')} |")
    return "\n".join(rows)


def write(form: str, src: dict) -> Path:
    filename, title = VERSIONS[form]
    other = VERSIONS["codes" if form == "greek" else "greek"][0]
    out = [
        "---",
        f'title: "{title}"',
        'subtitle: "Coded CPAT: the equations of the mitigation and distribution modules"',
        "format:",
        "  html:",
        "    toc: true",
        "    number-sections: false",
        "---",
        "",
        f"<!-- Generated by make_equations.py from equations.yaml: do not edit by hand. Other version: {other}. -->",
        "",
        src["intro"][form].strip(),
        "",
    ]
    for part in src["parts"]:
        out += [f"# {part['title']}", ""]
        if part.get("text"):
            out += [part["text"].strip(), ""]
        for section in part["sections"]:
            out += [f"## {section['title']}", ""]
            if section.get("text"):
                out += [section["text"].strip(), ""]
            for eq in section.get("equations", []):
                out.append(equation_block(eq, form))
    out += ["# Appendix: symbols and codes", "", src["symbols_text"].strip(), "", symbol_table(src["symbols"]), ""]
    path = HERE / filename
    path.write_text("\n".join(out), encoding="utf-8")
    return path


def check(src: dict) -> None:
    """Every equation has a unique id and both forms."""
    seen = set()
    for part in src["parts"]:
        for section in part["sections"]:
            for eq in section.get("equations", []):
                assert eq["id"] not in seen, f"duplicate id {eq['id']}"
                seen.add(eq["id"])
                for form in VERSIONS:
                    assert eq.get(form), f"{eq['id']}: no {form} form"


def main() -> None:
    src = yaml.safe_load(SOURCE.read_text(encoding="utf-8"))
    check(src)
    for form in VERSIONS:
        print("wrote", write(form, src).name)


if __name__ == "__main__":
    main()
