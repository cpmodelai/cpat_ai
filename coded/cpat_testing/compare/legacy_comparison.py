"""Phase 5.3: Coded CPAT's baseline against legacy CPAT's cached Egypt baseline (CPAT 1.0pre_456_NoPropData, the
values of its last full run: fuel use and after-tax prices by subsector and fuel, CO2 by subsector;
data/<edition>/tidy/xai_legacy_cached_baseline.csv). Writes legacy_comparison.md beside this file.

Coded CPAT equals Excel-AI code by code, so the gaps here are Excel-AI's gaps to legacy: legacy bugs fixed (L),
departures (LD, Excel-AI's LegacyDiff sheet) and data vintages (legacy 456 ran on older data). The report gives the fit
by variable and year and the largest gaps; the register (`excel_ai/BUGS.md`, `ISSUES.md`) explains them.

    python cpat_testing/compare/legacy_comparison.py
"""
import csv
import sys
import warnings
from pathlib import Path

import numpy as np

CODED = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(CODED))
from cpat_model.settings import edition  # noqa: E402

LEGACY = CODED.parent / 'data' / edition() / 'tidy' / 'xai_legacy_cached_baseline.csv'
REPORT = Path(__file__).with_name('legacy_comparison.md')
YEARS = [2022, 2025, 2030, 2035, 2040]
sys.path.insert(0, str(CODED))
warnings.filterwarnings('ignore')


def python_code(legacy_code, slots):
    """Legacy code -> Coded CPAT code: egy.mit.ener.rod.gso.e.1 -> egy.mit.ener.rod.gso.1 (legacy energy rows carry
    an '.e'); egy.mit.co2.<group>.<subsector>.1 -> the subsector's CO2 over all fuels."""
    parts = legacy_code.split('.')
    if parts[2] == 'co2' and len(parts) == 6:
        slot = slots.get(('co2', parts[4], 'all'))
        return f'egy.mit.{slot}.1' if slot else f'sum:egy.mit.co2.{parts[4]}.'   # the subsector's fuels, summed
    return legacy_code.replace('.e.1', '.1')


def gj_per_unit():
    """Legacy prices are per price unit (USD per liter for oil products); Coded CPAT's atp is per GJ."""
    with open(CODED / 'cpat_model' / 'core' / 'excel_ai' / 'fuels.csv', encoding='utf-8') as f:
        return {r['fuel']: float(r['gj_per_unit']) for r in csv.DictReader(f)}


def compare():
    import cpat_model
    from cpat_model.inputs import read_scenario_set
    from cpat_model.inputs.scenarios import ScenarioSet
    s = read_scenario_set()
    py = cpat_model.run(ScenarioSet(s.rows, ['1'])).by_code('EGY')
    with open(LEGACY, encoding='utf-8') as f:
        rows = list(csv.DictReader(f))
    from cpat_model.core import variables
    slots, gj = variables.slots(), gj_per_unit()
    out, unmatched = [], []
    for r in rows:
        code = python_code(r['code'], slots)
        if code and code.startswith('sum:'):                # CO2 of a subsector: no total row in Excel-AI's codes
            rows_ = [c for c in py.index if c.startswith(code[4:]) and c.endswith('.1') and c.count('.') == 5]
            code = code[4:] + 'tot.1'
            py.loc[code] = py.loc[rows_].apply(lambda c: c.astype(float)).sum() if rows_ else float('nan')
        if code not in py.index:
            unmatched.append(r['code'])
            continue
        for y in YEARS:
            lv, pv = float(r[str(y)] or 'nan'), float(py.loc[code, y])
            if code.split('.')[2] == 'atp':
                lv /= gj.get(code.split('.')[4], 1.0)       # per price unit -> per GJ
            if np.isnan(lv):
                continue
            out.append((code.split('.')[2], code, y, lv, pv, abs(pv - lv) / max(abs(lv), 1.0)))
    return out, unmatched, len(rows)


def report(out, unmatched, n):
    variables = sorted({o[0] for o in out})
    lines = ['# Coded CPAT against legacy CPAT (Egypt baseline)', '',
             'Generated by `legacy_comparison.py` (phase 5.3). Legacy: the cached baseline of `CPAT 1.0pre_456_NoPropData` '
             '(its last full run). Coded CPAT equals Excel-AI code by code, so these gaps are Excel-AI\'s: the legacy bugs it '
             'fixes (`excel_ai/BUGS.md`), its departures (LegacyDiff, `excel_ai/ISSUES.md` section 3) and newer data. '
             'Relative gap = |Coded - legacy| / max(|legacy|, 1); legacy prices converted from per price unit to per GJ.', '',
             f'{n} legacy rows; {n - len(unmatched)} compared; {len(unmatched)} without a Coded CPAT code.', '',
             '**Main causes of the gaps.** Prices: legacy 456 holds prices from its last historical year 2022, Excel-AI '
             'and Coded CPAT from 2024 (LastHistPriceYear) on newer domestic and international price data, and they '
             'fix the legacy price bugs (L-register, prices). Energy use and CO2 from 2023: they follow the prices '
             '(elasticities) and the fixed fuel-use and emission-factor bugs. The base year (2022) uses the same '
             'energy balance: energy use and CO2 agree closely there.', '',
             '| Variable | Year | Rows | Within 1% | Within 5% | Median gap | Largest gap |', '|---|---|---|---|---|---|---|']
    for v in variables:
        for y in YEARS:
            g = np.array([o[5] for o in out if o[0] == v and o[2] == y])
            if len(g):
                lines.append(f'| `{v}` | {y} | {len(g)} | {np.mean(g <= .01):.0%} | {np.mean(g <= .05):.0%} | '
                             f'{np.median(g):.3f} | {g.max():.3f} |')
    lines += ['', '## Largest gaps (2030)', '', '| Code | Legacy | Coded CPAT | Gap |', '|---|---|---|---|']
    for o in sorted((o for o in out if o[2] == 2030), key=lambda o: -o[5])[:15]:
        lines.append(f'| `{o[1]}` | {o[3]:.4g} | {o[4]:.4g} | {o[5]:.2f} |')
    if unmatched:
        lines += ['', 'Legacy rows without a Coded CPAT code: ' + ', '.join(f'`{c}`' for c in unmatched[:20])]
    REPORT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    return lines


if __name__ == '__main__':
    out, unmatched, n = compare()
    print('\n'.join(report(out, unmatched, n)[:40]))
